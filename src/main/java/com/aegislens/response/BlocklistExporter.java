package com.aegislens.response;

import com.aegislens.app.AllowList;
import com.aegislens.core.Finding;
import com.aegislens.db.BlockedIp;
import com.aegislens.util.IpRules;

import java.io.BufferedWriter;
import java.io.FileOutputStream;
import java.io.IOException;
import java.io.OutputStreamWriter;
import java.io.Writer;
import java.net.Inet4Address;
import java.net.InetAddress;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Instant;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import java.util.TreeSet;

/**
 * Turns the recorded blocks into files an admin can review and apply: a plain blocklist.txt plus ready-made command
 * files for iptables/ip6tables, nftables, ufw and Windows netsh. AegisLens NEVER runs them;
 * every file starts with a header saying so. Each address is parsed again and written in canonical form, so no text
 * from a log can ever reach a command line; private, local and allow-listed addresses are skipped with a reason.
 */
public final class BlocklistExporter {

    /** The files written, in this order. */
    public static final List<String> FILES = List.of("blocklist.txt", "iptables.sh", "nftables.nft", "ufw.sh", "windows-netsh.cmd");

    /** What was written and what was left out (address -> reason). */
    public record Result(int written, Map<String, String> skipped, List<Path> files) {
    }

    private final AllowList allowList;

    /** Addresses on this allow-list are never exported (they are the admin's own). */
    public BlocklistExporter(AllowList allowList) {
        this.allowList = allowList;
    }

    /** Writes the five files into {@code dir} (created if needed). Existing files with these names are replaced. */
    public Result export(List<BlockedIp> blocks, Path dir, Instant now) throws IOException {
        TreeSet<String> v4 = new TreeSet<>();
        TreeSet<String> v6 = new TreeSet<>();
        Map<String, String> skipped = new TreeMap<>();
        for (BlockedIp b : blocks) {
            String reason = IpRules.whyNotBlockable(b.ip()).orElse(null);
            if (reason == null && allowList.isTrusted(new Finding("export", b.ip(), "EXPORT", 0, "check"))) {
                reason = "on the allow-list";
            }
            if (reason != null) {
                skipped.put(b.ip(), reason);
                continue;
            }
            InetAddress ip = IpRules.blockable(b.ip());
            (ip instanceof Inet4Address ? v4 : v6).add(ip.getHostAddress());
        }
        Files.createDirectories(dir);
        List<Path> files = new ArrayList<>();
        files.add(write(dir.resolve(FILES.get(0)), header("#", now) + lines(v4, v6, "%s")));
        files.add(write(dir.resolve(FILES.get(1)), "#!/bin/sh\n" + header("#", now)
                + lines(v4, List.of(), "iptables -I INPUT -s %s -j DROP") + lines(List.of(), v6, "ip6tables -I INPUT -s %s -j DROP")));
        files.add(write(dir.resolve(FILES.get(2)), header("#", now) + nftables(v4, v6)));
        files.add(write(dir.resolve(FILES.get(3)), "#!/bin/sh\n" + header("#", now) + lines(v4, v6, "ufw deny from %s")));
        files.add(write(dir.resolve(FILES.get(4)), "@echo off\r\n" + header("REM", now).replace("\n", "\r\n")
                + lines(v4, v6, "netsh advfirewall firewall add rule name=\"AegisLens block %1$s\" dir=in action=block remoteip=%1$s")
                .replace("\n", "\r\n")));
        return new Result(v4.size() + v6.size(), skipped, files);
    }

    private static String header(String comment, Instant now) {
        return comment + " Generated by AegisLens on " + now + ".\n"
                + comment + " NOT executed by AegisLens. Review every line, then run it yourself as administrator.\n"
                + comment + " Only public addresses are listed; private, local and allow-listed ones were left out.\n";
    }

    private static String lines(Iterable<String> v4, Iterable<String> v6, String format) {
        StringBuilder sb = new StringBuilder();
        for (Iterable<String> family : List.of(v4, v6)) {
            for (String ip : family) {
                sb.append(String.format(format, ip)).append('\n');
            }
        }
        return sb.toString();
    }

    /** One table with a set per address family; an empty set is left out (nft refuses "elements = { }"). */
    private static String nftables(TreeSet<String> v4, TreeSet<String> v6) {
        StringBuilder sb = new StringBuilder("table inet aegislens {\n");
        if (!v4.isEmpty()) {
            sb.append("  set blocked4 { type ipv4_addr; elements = { ").append(String.join(", ", v4)).append(" } }\n");
        }
        if (!v6.isEmpty()) {
            sb.append("  set blocked6 { type ipv6_addr; elements = { ").append(String.join(", ", v6)).append(" } }\n");
        }
        sb.append("  chain input {\n    type filter hook input priority 0; policy accept;\n");
        if (!v4.isEmpty()) {
            sb.append("    ip saddr @blocked4 drop\n");
        }
        if (!v6.isEmpty()) {
            sb.append("    ip6 saddr @blocked6 drop\n");
        }
        return sb.append("  }\n}\n").toString();
    }

    private static Path write(Path file, String text) throws IOException {
        try (Writer w = new BufferedWriter(new OutputStreamWriter(new FileOutputStream(file.toFile()), StandardCharsets.UTF_8))) {
            w.write(text);
        }
        return file;
    }
}
